-- 1. Crear tabla para almacenar las respuestas del Test Big Five
create table if not exists public.big5_responses (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  full_name text not null,
  email text,
  
  -- Puntajes promedio (1.00 a 5.00)
  score_o numeric(4,2),
  score_c numeric(4,2),
  score_e numeric(4,2),
  score_a numeric(4,2),
  score_n numeric(4,2),
  
  -- Porcentajes calculados (0 a 100)
  percent_o integer,
  percent_c integer,
  percent_e integer,
  percent_a integer,
  percent_n integer,
  
  -- Niveles cualitativos (Bajo, Moderado, Alto)
  level_o text,
  level_c text,
  level_e text,
  level_a text,
  level_n text,
  
  -- Respuestas detalladas a las 44 preguntas en formato JSON
  answers jsonb
);

-- 2. Habilitar la seguridad a nivel de fila (Row Level Security - RLS)
alter table public.big5_responses enable row level security;

-- 3. Crear política para permitir que cualquier usuario que complete el test
-- pueda INSERTAR sus respuestas sin necesidad de iniciar sesión
drop policy if exists "Permitir insercion anonima" on public.big5_responses;
create policy "Permitir insercion anonima" 
  on public.big5_responses 
  for insert 
  with check (true);

